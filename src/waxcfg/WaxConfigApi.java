    private boolean sendWebhook(JsonObject payload) {
        if (testMode) {
            log("  [TEST] webhook simule edildi: " + hook);
            return true;
        }
        if (hookDead && !testMode) {
            log("  webhook olmu, istek atilmadi (404/401)");
            return false;
        }
        // mesaj abartisini onle: gonderimler arasi min 1.5sn
        long gap = System.currentTimeMillis() - lastWebhookMs;
        if (gap < 1500) sleep(1500 - gap);
        byte[] body = payload.toString().getBytes(StandardCharsets.UTF_8);
        for (int i = 0; i < 3; i++) {
            Resp r = httpCall(hook, K[0], body, K[6], null, 10);
            if (r != null && r.status >= 200 && r.status < 300) {
                lastWebhookMs = System.currentTimeMillis();
                return true;
            }
            if (r != null && (r.status == 404 || r.status == 401)) {
                // silinmis/yetkisiz webhook: yeniden denemenin anlami yok,
                // uzak config'den yeni h gelene kadar sessiz kal
                hookDead = true;
                deadHookUrl = hook;
                log("  webhook olmus (" + r.status + "), sonraki config degisimine kadar sessiz");
                return false;
            }
            if (r != null && r.status == 429) {
                JsonObject j = parseObj(r.body);
                long wait = 1200;
                if (j != null) {
                    JsonElement ra = j.get("retry_after");
                    if (ra != null && ra.isJsonPrimitive()) {
                        try { wait = (long) (ra.getAsJsonPrimitive().getAsDouble() * 1000); } catch (Exception ignored) { }
                    }
                }
                sleep(Math.min(Math.max(wait, 500), 15000));
                continue;
            }
            sleep(900);
        }
        return false;
    }

