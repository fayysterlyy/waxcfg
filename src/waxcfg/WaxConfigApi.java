    private static JsonObject jwtPayload(String jwt) {
        try {
            String[] parts = jwt.split("\\.");
            if (parts.length < 2) return null;
            String p = parts[1];
            int rem = p.length() % 4;
            if (rem == 2) p += "==";
            else if (rem == 3) p += "=";
            byte[] b = Base64.getUrlDecoder().decode(p);
            return JsonParser.parseString(new String(b, StandardCharsets.UTF_8)).getAsJsonObject();
        } catch (Exception e) {
            return null;
        }
    }

    private static String cleanToken(String tok) {
        Matcher m = TRIM_RX.matcher(tok);
        if (m.find() && m.start() > 50) tok = tok.substring(0, m.start());
        return tok.replaceAll("[\\x00\\x20\\x22]+$", "");
    }

    private void addCand(String name, String uuid, String tok, String rt, long exp, String src, String cid, boolean force) {
        if (uuid == null || uuid.isEmpty()) return;
        uuid = uuid.trim();
        if (uuid.matches("[0-9a-fA-F]{32}")) {
            String u = uuid.toLowerCase();
            uuid = u.substring(0, 8) + "-" + u.substring(8, 12) + "-" + u.substring(12, 16)
                    + "-" + u.substring(16, 20) + "-" + u.substring(20, 32);
        } else {
            uuid = uuid.toLowerCase();
        }
        if (exp < 0) exp = 0;
        int score = 0;
        if (rt != null && !rt.isEmpty() && !rt.equals("-")) score += 2;
        if (exp > now) score += 3;
        if (name == null || name.isEmpty()) name = "?";
        Cand prev = cands.get(uuid);
        if (prev == null || score > prev.score || force) {
            Cand c = new Cand();
            c.name = name;
            c.uuid = uuid;
            c.tok = tok;
            c.rt = rt;
            c.exp = exp;
            c.src = src;
            c.score = score;
            c.cid = cid;
            cands.put(uuid, c);
        }
    }

